import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));

// file:// pages cannot hand a local PNG to WebGL: Chrome taints the image and
// texSubImage2D throws. The bundle therefore carries the photographic textures
// as data URLs. JPEG keeps that payload small (the sources are opaque
// photographs), and the conversion is done with the Windows imaging stack.
function inlineTextures(dirName) {
  const dir = join(root, 'dist/assets/textures', dirName);
  const names = readdirSync(dir).filter((n) => n.endsWith('.png'));
  if (!names.length) return {};
  const out = mkdtempSync(join(tmpdir(), `${dirName}-tex-`));
  try {
    const script = [
      'Add-Type -AssemblyName System.Drawing',
      `$dir='${dir.replace(/'/g, "''")}';$out='${out.replace(/'/g, "''")}'`,
      '$enc=[System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders()|Where-Object{$_.MimeType -eq "image/jpeg"}',
      '$p=New-Object System.Drawing.Imaging.EncoderParameters(1)',
      '$p.Param[0]=New-Object System.Drawing.Imaging.EncoderParameter([System.Drawing.Imaging.Encoder]::Quality,84)',
      'Get-ChildItem "$dir\\*.png"|ForEach-Object{$i=[System.Drawing.Image]::FromFile($_.FullName);$i.Save("$out\\$($_.BaseName).jpg",$enc,$p);$i.Dispose()}',
    ].join(';');
    execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', script], { stdio: 'ignore' });
    const map = {};
    for (const name of names) {
      const base = name.replace(/\.png$/, '');
      const data = readFileSync(join(out, `${base}.jpg`));
      map[`assets/textures/${dirName}/${name}`] = `data:image/jpeg;base64,${data.toString('base64')}`;
    }
    return map;
  } catch (error) {
    console.warn(`build:local — could not inline ${dirName} textures for file://`, error.message);
    return {};
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

const localTextures = { ...inlineTextures('guomao'), ...inlineTextures('river') };

await build({
  absWorkingDir: root,
  entryPoints: ['dist/js/main.js'],
  outfile: 'dist/js/local.bundle.js',
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  alias: {
    three: './dist/vendor/three.module.js',
    'three/addons/utils/BufferGeometryUtils.js': './dist/vendor/BufferGeometryUtils.js',
  },
  minify: true,
  legalComments: 'eof',
  banner: {
    js: `/* Generated by npm run build:local. Licenses are in ../assets/. */\n`
      + `globalThis.__LOCAL_TEXTURES__=${JSON.stringify(localTextures)};`,
  },
});
